function startQuiz(type,list){
  let p=list||shuffle(pool());
  if(!list&&st.n!=='all')p=p.slice(0,+st.n);
  if(type==='choice'&&W.length<4)return;
  session={type,q:p,i:0,ok:[],ng:[],answered:false};
}
function quizHeader(s){
  return `<div class="row" style="justify-content:space-between"><span class="count">${s.i+1} / ${s.q.length}　正解 ${s.ok.length}</span>
    <span class="row">${s.type==='choice'?`<select id="qdir" aria-label="向き"><option value="en">英 → 日</option><option value="ja">日 → 英</option></select>`:''}
    <select id="qn" aria-label="問題数"><option value="10">10問</option><option value="20">20問</option><option value="all">全部</option></select></span></div>
    <div class="bar"><i style="width:${s.i/s.q.length*100}%"></i></div>`;
}
function bindHeader(){
  $('#qn').value=st.n;$('#qn').onchange=e=>{st.n=e.target.value;session=null;render()};
  if($('#qdir')){$('#qdir').value=st.choiceDir;$('#qdir').onchange=e=>{st.choiceDir=e.target.value;session=null;render()}}
}
function feedback(ok,w,extra=''){
  return `<div class="fb ${ok?'ok':'ng'}"><b>${ok?'正解':'不正解'}</b>　<span class="en" style="color:var(--fg)">${esc(w.w)}</span> ${sayBtn(w.w)} ＝ ${esc(w.m)}${extra}
    <div class="detail en" style="font-weight:500">${exHTML(w)}</div><div class="detail">${esc(w.ja)}</div></div>
    <div class="row center"><button class="btn primary" id="next">次へ（Enter）</button></div>`;
}
function record(ok){const s=session,w=s.q[s.i];s.answered=true;s.last=ok;mark(w.id,ok);(ok?s.ok:s.ng).push(w);renderChips()}
function next(){session.i++;session.answered=false;render()}

function renderChoice(){
  if(!session){if(!pool().length){V().innerHTML='<div class="empty">この範囲に単語がありません。</div>';return}startQuiz('choice')}
  const s=session;if(s.i>=s.q.length)return renderResult();
  const w=s.q[s.i],en=st.choiceDir==='en';
  if(!s.opts||s.optsFor!==s.i){
    const same=shuffle(W.filter(x=>x.id!==w.id&&x.pos===w.pos)),other=shuffle(W.filter(x=>x.id!==w.id&&x.pos!==w.pos));
    s.opts=shuffle([w,...same.concat(other).slice(0,3)]);s.optsFor=s.i;
  }
  const lab=x=>en?esc(x.m):`<span class="en">${esc(x.w)}</span>`;
  V().innerHTML=`<div class="q">${quizHeader(s)}
    <div class="prompt ${en?'en':'ja'}">${en?esc(w.w)+' '+sayBtn(w.w):esc(w.m)}</div>
    <div class="choices">${s.opts.map((o,k)=>`<button class="choice" data-k="${k}" ${s.answered?'disabled':''}><span class="num">${k+1}</span>　${lab(o)}</button>`).join('')}</div>
    <div id="fbx"></div></div>`;
  bindHeader();
  V().querySelectorAll('.choice').forEach(b=>b.onclick=()=>{
    if(s.answered)return;const o=s.opts[+b.dataset.k],ok=o.id===w.id;record(ok);
    V().querySelectorAll('.choice').forEach(c=>{const x=s.opts[+c.dataset.k];if(x.id===w.id)c.classList.add('right');else if(c===b)c.classList.add('wrong');c.disabled=true});
    $('#fbx').innerHTML=feedback(ok,w);$('#next').onclick=next;$('#next').focus();
  });
}

function renderTyping(kind){
  if(!session){if(!pool().length){V().innerHTML='<div class="empty">この範囲に単語がありません。</div>';return}startQuiz(kind)}
  const s=session;if(s.i>=s.q.length)return renderResult();
  const w=s.q[s.i],target=kind==='spell'?w.w:w.ans;
  const hint=`ヒント：${esc(target[0])}${'＿'.repeat(Math.max(0,target.replace(/ /g,'').length-1))}（${target.replace(/ /g,'').length}文字${target.includes(' ')?'・2語':''}）`;
  const body=kind==='spell'
    ?`<div class="prompt ja">${esc(w.m)}</div><div class="hint" style="text-align:center">${POSN[w.pos]}</div>`
    :`<div class="sent">${esc(w.ex).replace(/\[(.+?)\]/,'<span class="blank">　?　</span>')}</div><div style="text-align:center">${esc(w.ja)}</div>`;
  V().innerHTML=`<div class="q">${quizHeader(s)}${body}
    <div class="hint" style="text-align:center">${hint}</div>
    <form id="f" class="q"><input class="answer-in" id="ans" autocomplete="off" autocapitalize="off" spellcheck="false" aria-label="答え" placeholder="英語で入力">
    <div class="row center"><button class="btn" type="button" id="giveup">わからない</button><button class="btn primary" type="submit">答える</button></div></form>
    <div id="fbx"></div></div>`;
  bindHeader();
  const inp=$('#ans');inp.focus();
  const done=ok=>{record(ok);inp.disabled=true;$('#f').querySelectorAll('button').forEach(b=>b.disabled=true);
    const extra=kind==='cloze'&&!ok?`<div class="detail">答え：<b class="en">${esc(target)}</b>${target.toLowerCase()!==w.w.toLowerCase()?`（${esc(w.w)} の変化形）`:''}</div>`:(!ok&&inp.value?`<div class="detail">あなたの答え：<span class="en">${esc(inp.value)}</span></div>`:'');
    $('#fbx').innerHTML=feedback(ok,w,extra);$('#next').onclick=next;$('#next').focus()};
  $('#f').onsubmit=e=>{e.preventDefault();if(s.answered||!inp.value.trim())return;done(norm(inp.value)===norm(target))};
  $('#giveup').onclick=()=>{if(!s.answered)done(false)};
}

function renderResult(){
  const s=session,total=s.q.length,isCard=s.type==='card';
  V().innerHTML=`<div class="q">
    <div class="score">${s.ok.length}<small> / ${total}</small></div>
    <div style="text-align:center;color:var(--muted)">${isCard?'覚えた数':'正解数'}</div>
    ${s.ng.length?`<div><b>${isCard?'まだの単語':'間違えた単語'}</b><ul class="miss">${s.ng.map(w=>`<li><span class="num">${w.id}</span>　<span class="en">${esc(w.w)}</span>　${esc(w.m)}</li>`).join('')}</ul></div>`:'<div style="text-align:center;color:var(--ok);font-weight:700">全部できました！</div>'}
    <div class="row center">${s.ng.length?`<button class="btn bad" id="retryNg">間違えたものだけもう一度</button>`:''}<button class="btn primary" id="again">もう一度（新しく出題）</button></div></div>`;
  if(s.ng.length)$('#retryNg').onclick=()=>{const ng=shuffle(s.ng);if(isCard)session={type:'card',q:ng,i:0,flip:false,ok:[],ng:[]};else startQuiz(s.type,ng);render()};
  $('#again').onclick=()=>{session=null;render()};
}

function render(){({list:renderList,card:renderCard,choice:renderChoice,spell:()=>renderTyping('spell'),cloze:()=>renderTyping('cloze')})[st.mode]()}

document.addEventListener('keydown',e=>{
  const s=session;if(!s)return;
  if(st.mode==='card'&&s.i<s.q.length&&e.target.tagName!=='SELECT'){
    if(!s.flip&&(e.key===' '||e.key==='Enter')){e.preventDefault();s.flip=true;renderCard()}
    else if(s.flip&&e.key==='ArrowRight')cardNext(true);
    else if(s.flip&&e.key==='ArrowLeft')cardNext(false);
  }else if(st.mode==='choice'&&!s.answered&&/^[1-4]$/.test(e.key)){const b=V().querySelector(`.choice[data-k="${+e.key-1}"]`);b&&b.click()}
  else if(s.answered&&e.key==='Enter'&&$('#next')&&document.activeElement!==$('#next')){e.preventDefault();next()}
});

